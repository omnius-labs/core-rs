    #[tokio::test]
    async fn semantic_errors_leave_existing_destinations_unchanged() {
        let temp_dir = tempfile::tempdir().unwrap();
        let source_dir = temp_dir.path().join("rpfs");
        let output_dir = temp_dir.path().join("gen/src");
        fs::create_dir_all(&source_dir).unwrap();
        fs::create_dir_all(&output_dir).unwrap();
        fs::write(source_dir.join("schema.rpf"), "version 1; package test; const LIMIT: u8 = 300;").unwrap();
        let output_path = output_dir.join("rocketpack.rs");
        fs::write(&output_path, "unchanged").unwrap();
        let manifest = temp_dir.path().join("rocketpack.yaml");
        fs::write(
            &manifest,
            "version: 1\nname: test\nsources:\n  - base_dir: rpfs\n    includes:\n      - '**/*.rpf'\ngenerators:\n  - id: rust\n    plugin: rocketpack-rust\n    options:\n      output_dir: gen/src\n      module_name: rocketpack\n",
        )
        .unwrap();

        let manifests = ManifestGraph::load(&manifest).await.unwrap();
        assert!(SemanticGraph::build(manifests).is_err());
        assert_eq!(fs::read_to_string(output_path).unwrap(), "unchanged");
    }
