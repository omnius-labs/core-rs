fn render_literal(literal: &Literal) -> Result<String, CodegenError> {
    Ok(match literal {
        Literal::Bool(value) => value.to_string(),
        Literal::Int(value) => value.to_string(),
        Literal::Float(value) => {
            let mut rendered = value.to_string();
            if !rendered.contains('.') && !rendered.contains('e') && !rendered.contains('E') {
                rendered.push_str(".0");
            }
            rendered
        }
        Literal::String(value) => format!("{value:?}"),
        Literal::Bytes(bytes) => {
            let rendered = bytes.iter().map(|byte| byte.to_string()).collect::<Vec<_>>().join(", ");
            format!("vec![{rendered}]")
        }
        Literal::Some(value) => format!("Some({})", render_literal(value)?),
        Literal::None => "None".to_string(),
    })
}

fn internal_module_name(file: &crate::semantic::SchemaFile) -> String {
    let stem = file
        .relative_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or("source")
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() || ch == '_' { ch } else { '_' })
        .collect::<String>();
    let identity = format!("{}:{}", file.owner, file.relative_path.display());
    format!("__rpf_{}_{:016x}", stem, stable_hash(identity.as_bytes()))
}

fn stable_hash(bytes: &[u8]) -> u64 {
    let mut hash = 0xcbf29ce484222325_u64;
    for byte in bytes {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    hash
}

fn validate_relative_output_dir(output_dir: &str) -> Result<(), CodegenError> {
    if output_dir.is_empty() {
        return Err(CodegenError::Other("rust output_dir must not be empty".to_string()));
    }
    let path = FsPath::new(output_dir);
    if path.is_absolute()
        || path
            .components()
            .any(|component| matches!(component, Component::ParentDir | Component::RootDir | Component::Prefix(_)))
    {
        return Err(CodegenError::Other(format!(
            "rust output_dir must be a relative path without parent traversal: {output_dir}"
        )));
    }
    Ok(())
}

fn validate_rust_ident(value: &str, field: &str) -> Result<(), CodegenError> {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return Err(CodegenError::Other(format!("{field} must not be empty")));
    };
    if !(first == '_' || first.is_ascii_alphabetic()) || !chars.all(|ch| ch == '_' || ch.is_ascii_alphanumeric()) || is_rust_keyword(value) {
        return Err(CodegenError::Other(format!("{field} is not a valid Rust identifier: `{value}`")));
    }
    Ok(())
}

