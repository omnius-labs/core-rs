const GENERATED_MARKER: &str = "// @generated by rocketpack-compiler";

/// 生成ファイルの先頭に置く inner attribute。
/// `.rpf` の識別子は Rust の命名規則へ寄せずそのまま出力するため、
/// `nonstandard_style` (`non_camel_case_types` など) を module 単位で抑止する。
/// outer attribute だと直後の item にしか効かないので inner attribute で書き出す。
const GENERATED_INNER_ATTRIBUTES: &[&str] = &["#![allow(dead_code)]", "#![allow(nonstandard_style)]", "#![allow(clippy::all)]"];

fn write_generated_header(out: &mut String) {
    writeln!(out, "{GENERATED_MARKER}").ok();
    for attribute in GENERATED_INNER_ATTRIBUTES {
        writeln!(out, "{attribute}").ok();
    }
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct RustOptions {
    output_dir: String,
    module_name: String,
    #[serde(default)]
    dependencies: BTreeMap<String, RustDependencyOptions>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct RustDependencyOptions {
    #[serde(rename = "crate")]
    crate_name: String,
    module_name: String,
}

#[derive(Debug, Default)]
struct PackageNode {
    children: BTreeSet<String>,
    files: Vec<usize>,
}

#[derive(Clone, Copy)]
struct RustFileContext<'a> {
    graph: &'a SemanticGraph,
    file_index: usize,
    options: &'a RustOptions,
}

