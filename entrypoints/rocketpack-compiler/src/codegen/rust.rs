fn publish_generated_files(root_dir: &FsPath, options: &RustOptions, generated_files: &BTreeMap<PathBuf, String>) -> Result<usize, CodegenError> {
    let root_dir = fs::canonicalize(root_dir)?;
    let output_dir = root_dir.join(&options.output_dir);
    ensure_output_dir_inside_root(&root_dir, &output_dir)?;
    fs::create_dir_all(&output_dir)?;
    let output_dir = fs::canonicalize(output_dir)?;
    if !output_dir.starts_with(&root_dir) {
        return Err(CodegenError::Other(format!("rust output_dir escapes manifest root: {}", output_dir.display())));
    }

    let target_file = output_dir.join(format!("{}.rs", options.module_name));
    let target_dir = output_dir.join(&options.module_name);
    let backup_file = output_dir.join(format!(".rocketpack-{}.rs.backup", options.module_name));
    let backup_dir = output_dir.join(format!(".rocketpack-{}.backup", options.module_name));
    cleanup_stale_stages(&output_dir, &options.module_name)?;
    recover_backup(&target_file, &backup_file)?;
    recover_backup(&target_dir, &backup_dir)?;
    validate_managed_target(&target_file)?;
    validate_managed_target(&target_dir)?;

    let stage = tempfile::Builder::new()
        .prefix(&format!(".rocketpack-{}.stage-", options.module_name))
        .tempdir_in(&output_dir)?;
    for (relative_path, contents) in generated_files {
        let path = stage.path().join(relative_path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, contents)?;
    }
    fs::create_dir_all(stage.path().join(&options.module_name))?;

    move_to_backup(&target_file, &backup_file)?;
    if let Err(err) = move_to_backup(&target_dir, &backup_dir) {
        restore_backup(&target_file, &backup_file)?;
        return Err(err);
    }

    let staged_file = stage.path().join(format!("{}.rs", options.module_name));
    let staged_dir = stage.path().join(&options.module_name);
    if let Err(err) = fs::rename(&staged_file, &target_file) {
        restore_backup(&target_file, &backup_file)?;
        restore_backup(&target_dir, &backup_dir)?;
        return Err(err.into());
    }
    if let Err(err) = fs::rename(&staged_dir, &target_dir) {
        let _ = fs::remove_file(&target_file);
        restore_backup(&target_file, &backup_file)?;
        restore_backup(&target_dir, &backup_dir)?;
        return Err(err.into());
    }

    remove_target(&backup_file)?;
    remove_target(&backup_dir)?;
    Ok(generated_files.len())
}

fn cleanup_stale_stages(output_dir: &FsPath, module_name: &str) -> Result<(), CodegenError> {
    let prefix = format!(".rocketpack-{module_name}.stage-");
    for entry in fs::read_dir(output_dir)? {
        let entry = entry?;
        if entry.file_name().to_string_lossy().starts_with(&prefix) {
            let path = entry.path();
            validate_managed_target(&path)?;
            remove_target(&path)?;
        }
    }
    Ok(())
}

fn ensure_output_dir_inside_root(root_dir: &FsPath, output_dir: &FsPath) -> Result<(), CodegenError> {
    let mut existing = output_dir;
    while !existing.exists() {
        existing = existing
            .parent()
            .ok_or_else(|| CodegenError::Other("rust output_dir has no existing ancestor".to_string()))?;
    }
    let existing = fs::canonicalize(existing)?;
    if !existing.starts_with(root_dir) {
        return Err(CodegenError::Other(format!("rust output_dir escapes manifest root: {}", output_dir.display())));
    }
    Ok(())
}

fn validate_managed_target(path: &FsPath) -> Result<(), CodegenError> {
    if !path.exists() {
        return Ok(());
    }
    let metadata = fs::symlink_metadata(path)?;
    if metadata.file_type().is_symlink() {
        return Err(CodegenError::Other(format!("refusing to replace symlinked generated target: {}", path.display())));
    }
    if metadata.is_file() {
        let contents = fs::read_to_string(path)?;
        if !contents.starts_with(GENERATED_MARKER) {
            return Err(CodegenError::Other(format!("refusing to replace unmanaged file: {}", path.display())));
        }
        return Ok(());
    }
    if metadata.is_dir() {
        for entry in fs::read_dir(path)? {
            validate_managed_target(&entry?.path())?;
        }
        return Ok(());
    }
    Err(CodegenError::Other(format!("unsupported generated target type: {}", path.display())))
}

fn recover_backup(target: &FsPath, backup: &FsPath) -> Result<(), CodegenError> {
    if !backup.exists() {
        return Ok(());
    }
    validate_managed_target(backup)?;
    if target.exists() {
        return Err(CodegenError::Other(format!(
            "both generated target and interrupted backup exist: {} and {}",
            target.display(),
            backup.display()
        )));
    }
    fs::rename(backup, target)?;
    Ok(())
}

fn move_to_backup(target: &FsPath, backup: &FsPath) -> Result<(), CodegenError> {
    if target.exists() {
        fs::rename(target, backup)?;
    }
    Ok(())
}

fn restore_backup(target: &FsPath, backup: &FsPath) -> Result<(), CodegenError> {
    if backup.exists() {
        if target.exists() {
            remove_target(target)?;
        }
        fs::rename(backup, target)?;
    }
    Ok(())
}

fn remove_target(path: &FsPath) -> Result<(), CodegenError> {
    if !path.exists() {
        return Ok(());
    }
    if path.is_dir() {
        fs::remove_dir_all(path)?;
    } else {
        fs::remove_file(path)?;
    }
    Ok(())
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

fn sanitize_ident(value: &str) -> String {
    if is_rust_keyword(value) && !matches!(value, "self" | "Self" | "super" | "crate") {
        format!("r#{value}")
    } else if matches!(value, "self" | "Self" | "super" | "crate") {
        format!("{value}_")
    } else {
        value.to_string()
    }
}

